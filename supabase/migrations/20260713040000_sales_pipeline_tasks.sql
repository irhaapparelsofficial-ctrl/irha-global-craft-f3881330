CREATE TABLE IF NOT EXISTS public.crm_tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  source_type text NOT NULL CHECK (source_type IN ('inquiry', 'catalogue', 'prospect')),
  source_id uuid NOT NULL,
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 2 AND 240),
  notes text,
  priority text NOT NULL DEFAULT 'normal' CHECK (priority IN ('low', 'normal', 'high', 'urgent')),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'completed', 'cancelled')),
  due_at timestamptz,
  assigned_to text,
  completed_at timestamptz,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((status = 'completed' AND completed_at IS NOT NULL) OR status <> 'completed')
);

CREATE INDEX IF NOT EXISTS crm_tasks_source_idx
  ON public.crm_tasks (source_type, source_id, status);
CREATE INDEX IF NOT EXISTS crm_tasks_due_open_idx
  ON public.crm_tasks (due_at, priority)
  WHERE status = 'open';
CREATE INDEX IF NOT EXISTS crm_tasks_assignee_open_idx
  ON public.crm_tasks (assigned_to, due_at)
  WHERE status = 'open';

CREATE TABLE IF NOT EXISTS public.crm_activity_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_type text NOT NULL CHECK (source_type IN ('inquiry', 'catalogue', 'prospect')),
  source_id uuid NOT NULL,
  event_type text NOT NULL CHECK (event_type IN (
    'stage_changed', 'follow_up_scheduled', 'task_created', 'task_completed',
    'note_added', 'email_drafted', 'email_sent', 'whatsapp_opened',
    'quotation_created', 'quotation_sent', 'sample_updated', 'meeting_scheduled',
    'record_updated', 'system'
  )),
  summary text NOT NULL CHECK (char_length(btrim(summary)) BETWEEN 2 AND 500),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS crm_activity_events_source_created_idx
  ON public.crm_activity_events (source_type, source_id, created_at DESC);
CREATE INDEX IF NOT EXISTS crm_activity_events_type_created_idx
  ON public.crm_activity_events (event_type, created_at DESC);

ALTER TABLE public.crm_tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.crm_activity_events ENABLE ROW LEVEL SECURITY;

