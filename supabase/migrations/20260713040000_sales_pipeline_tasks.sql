CREATE OR REPLACE FUNCTION public.crm_task_before_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT public.has_role(auth.uid(), 'admin') THEN
    RAISE EXCEPTION 'admin access required' USING ERRCODE = '42501';
  END IF;

  NEW.title := btrim(NEW.title);
  NEW.updated_at := now();
  NEW.updated_by := auth.uid();
  IF TG_OP = 'INSERT' THEN
    NEW.created_by := COALESCE(NEW.created_by, auth.uid());
  END IF;
  IF NEW.status = 'completed' AND NEW.completed_at IS NULL THEN
    NEW.completed_at := now();
  ELSIF NEW.status <> 'completed' THEN
    NEW.completed_at := NULL;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS crm_task_before_write_trigger ON public.crm_tasks;
CREATE TRIGGER crm_task_before_write_trigger
  BEFORE INSERT OR UPDATE ON public.crm_tasks
  FOR EACH ROW EXECUTE FUNCTION public.crm_task_before_write();

CREATE OR REPLACE FUNCTION public.crm_task_activity_audit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.crm_activity_events (
      source_type, source_id, event_type, summary, metadata, actor_id
    ) VALUES (
      NEW.source_type,
      NEW.source_id,
      'task_created',
      'Task created: ' || NEW.title,
      jsonb_build_object('task_id', NEW.id, 'priority', NEW.priority, 'due_at', NEW.due_at),
      auth.uid()
    );
  ELSIF TG_OP = 'UPDATE' AND OLD.status IS DISTINCT FROM NEW.status AND NEW.status = 'completed' THEN
    INSERT INTO public.crm_activity_events (
      source_type, source_id, event_type, summary, metadata, actor_id
    ) VALUES (
      NEW.source_type,
      NEW.source_id,
      'task_completed',
      'Task completed: ' || NEW.title,
      jsonb_build_object('task_id', NEW.id),
      auth.uid()
    );
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS crm_task_activity_audit_trigger ON public.crm_tasks;
CREATE TRIGGER crm_task_activity_audit_trigger
  AFTER INSERT OR UPDATE ON public.crm_tasks
  FOR EACH ROW EXECUTE FUNCTION public.crm_task_activity_audit();

REVOKE ALL ON FUNCTION public.crm_task_before_write() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.crm_task_activity_audit() FROM PUBLIC;

