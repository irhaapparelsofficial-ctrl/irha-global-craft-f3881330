CREATE TABLE IF NOT EXISTS public.media_assets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  bucket text NOT NULL DEFAULT 'site-media',
  object_path text NOT NULL UNIQUE,
  public_url text NOT NULL,
  file_name text NOT NULL,
  mime_type text NOT NULL,
  size_bytes bigint NOT NULL CHECK (size_bytes >= 0 AND size_bytes <= 26214400),
  title text,
  alt_text text,
  tags text[] NOT NULL DEFAULT '{}',
  usage_notes text,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived')),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS media_assets_status_created_idx
  ON public.media_assets (status, created_at DESC);
CREATE INDEX IF NOT EXISTS media_assets_tags_gin_idx
  ON public.media_assets USING gin (tags);

CREATE TABLE IF NOT EXISTS public.media_asset_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  media_asset_id uuid REFERENCES public.media_assets(id) ON DELETE SET NULL,
  action text NOT NULL CHECK (action IN ('insert', 'update', 'delete')),
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  before_record jsonb,
  after_record jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.media_assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.media_asset_events ENABLE ROW LEVEL SECURITY;

