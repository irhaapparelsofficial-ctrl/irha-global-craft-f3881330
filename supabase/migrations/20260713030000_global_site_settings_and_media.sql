CREATE OR REPLACE FUNCTION public.media_assets_before_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT public.has_role(auth.uid(), 'admin') THEN
    RAISE EXCEPTION 'admin access required' USING ERRCODE = '42501';
  END IF;
  NEW.updated_at := now();
  NEW.updated_by := auth.uid();
  IF TG_OP = 'INSERT' THEN NEW.created_by := COALESCE(NEW.created_by, auth.uid()); END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.media_assets_audit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.media_asset_events (media_asset_id, action, actor_id, before_record, after_record)
  VALUES (
    COALESCE(NEW.id, OLD.id),
    lower(TG_OP),
    auth.uid(),
    CASE WHEN TG_OP IN ('UPDATE','DELETE') THEN to_jsonb(OLD) ELSE NULL END,
    CASE WHEN TG_OP IN ('INSERT','UPDATE') THEN to_jsonb(NEW) ELSE NULL END
  );
  RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS media_assets_before_write_trigger ON public.media_assets;
CREATE TRIGGER media_assets_before_write_trigger
  BEFORE INSERT OR UPDATE ON public.media_assets
  FOR EACH ROW EXECUTE FUNCTION public.media_assets_before_write();

DROP TRIGGER IF EXISTS media_assets_audit_trigger ON public.media_assets;
CREATE TRIGGER media_assets_audit_trigger
  AFTER INSERT OR UPDATE OR DELETE ON public.media_assets
  FOR EACH ROW EXECUTE FUNCTION public.media_assets_audit();

REVOKE ALL ON FUNCTION public.media_assets_before_write() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.media_assets_audit() FROM PUBLIC;

