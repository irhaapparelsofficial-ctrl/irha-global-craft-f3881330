create index if not exists search_measurement_runs_completed_idx
  on public.search_measurement_runs (completed_at desc) where status = 'complete';
create index if not exists search_console_observations_run_dimension_idx
  on public.search_console_observations (run_id, period, dimension_type, impressions desc);
