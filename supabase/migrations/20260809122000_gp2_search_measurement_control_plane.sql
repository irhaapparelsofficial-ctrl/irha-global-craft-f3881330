  on public.search_console_observations (run_id, period, canonical_path) where canonical_path is not null;

create or replace view public.gp2_product_search_observability as
with latest as (
  select id, completed_at
  from public.search_measurement_runs
  where status = 'complete'
  order by completed_at desc nulls last
  limit 1
), search_by_path as (
  select o.canonical_path,
         sum(o.clicks) as clicks,
         sum(o.impressions) as impressions,
         case when sum(o.impressions) > 0 then sum(o.clicks) / sum(o.impressions) else null end as ctr,
         case when sum(o.impressions) > 0 then sum(o.position * o.impressions) / sum(o.impressions) else null end as average_position
  from public.search_console_observations o
  join latest l on l.id = o.run_id
  where o.period = 'current_28d' and o.dimension_type = 'page'
  group by o.canonical_path
), intent_by_product as (
  select product_id,
         count(*) filter (where event_name = 'product_view') as product_views,
         count(*) filter (where event_name in ('inquiry_cta_click','whatsapp_click','email_click','sample_cta_click','quote_cta_click','rfq_start')) as intent_events,
         count(*) filter (where event_name in ('rfq_submit','general_inquiry_submit','product_inquiry_submit')) as submit_events,
         max(occurred_at) as last_intent_observed_at
  from public.commercial_measurement_events
  where occurred_at >= clock_timestamp() - interval '28 days'
  group by product_id
)
select p.id as product_id,
       p.reference_code,
       p.sku,
       p.name,
       p.main_category,
       p.audience_group,
       p.product_type,
       p.canonical_path,
       s.impressions,
       s.clicks,
       s.ctr,
       s.average_position,
       coalesce(i.product_views, 0) as product_views,
       coalesce(i.intent_events, 0) as intent_events,
       coalesce(i.submit_events, 0) as submit_events,
       i.last_intent_observed_at,
       l.completed_at as search_last_observed_at,
       case when s.canonical_path is null then 'NO DATA / NOT OBSERVED' else 'OBSERVED' end as search_data_state
from public.products p
left join search_by_path s on s.canonical_path = p.canonical_path
left join intent_by_product i on i.product_id = p.id
left join latest l on true
where p.is_published = true and p.publish_state = 'published';

create or replace view public.gp2_category_observability as
select p.main_category,
       count(*) as published_products,
       count(*) filter (where o.search_data_state = 'OBSERVED') as products_with_search_data,
       sum(coalesce(o.impressions, 0)) as observed_impressions,
       sum(coalesce(o.clicks, 0)) as observed_clicks,
       sum(coalesce(o.product_views, 0)) as product_views,
       sum(coalesce(o.intent_events, 0)) as intent_events,
       sum(coalesce(o.submit_events, 0)) as submit_events,
       max(o.search_last_observed_at) as search_last_observed_at
from public.products p
left join public.gp2_product_search_observability o on o.product_id = p.id
where p.is_published = true and p.publish_state = 'published'
group by p.main_category;

revoke all on public.gp2_product_search_observability from public, anon, authenticated;
revoke all on public.gp2_category_observability from public, anon, authenticated;
grant select on public.gp2_product_search_observability to service_role;
grant select on public.gp2_category_observability to service_role;

