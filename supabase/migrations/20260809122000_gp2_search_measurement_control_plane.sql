-- IRHA GP-2 — Search measurement / commercial observability control plane.
-- Additive, RLS-first, no product/catalogue content mutation.

create table if not exists public.commercial_measurement_events (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default clock_timestamp(),
  event_name text not null check (event_name in (
    'page_view','organic_landing','campaign_landing','category_view','product_type_view','product_view',
    'manufacturing_resource_view','inquiry_cta_click','whatsapp_click','email_click','sample_cta_click',
    'quote_cta_click','rfq_start','rfq_submit','general_inquiry_submit','product_inquiry_submit'
  )),
  anonymous_session_hash text check (anonymous_session_hash is null or anonymous_session_hash ~ '^[0-9a-f]{64}$'),
  canonical_path text not null default '/',
  landing_path text,
  referrer_host text,
  source text,
  medium text,
  campaign text,
  content text,
  term text,
  product_id uuid references public.products(id) on delete set null,
  reference_code text,
  main_category text,
  audience_group text,
  product_type text,
  country_code text check (country_code is null or country_code ~ '^[A-Z]{2}$'),
  device_type text check (device_type is null or device_type in ('mobile','tablet','desktop','unknown')),
  lead_kind text,
  lead_reference text,
  evidence jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default clock_timestamp()
);

alter table public.commercial_measurement_events enable row level security;
revoke all on table public.commercial_measurement_events from public, anon, authenticated;
grant select, insert on table public.commercial_measurement_events to service_role;
grant usage, select on sequence public.commercial_measurement_events_id_seq to service_role;

create index if not exists commercial_measurement_events_name_time_idx
  on public.commercial_measurement_events (event_name, occurred_at desc);
create index if not exists commercial_measurement_events_path_time_idx
  on public.commercial_measurement_events (canonical_path, occurred_at desc);
create index if not exists commercial_measurement_events_product_time_idx
  on public.commercial_measurement_events (product_id, occurred_at desc) where product_id is not null;
create index if not exists commercial_measurement_events_source_time_idx
  on public.commercial_measurement_events (source, medium, occurred_at desc);

create table if not exists public.search_measurement_runs (
  id uuid primary key default gen_random_uuid(),
  property text not null default 'sc-domain:irhaapparels.com',
  started_at timestamptz not null default clock_timestamp(),
  completed_at timestamptz,
  status text not null check (status in ('running','complete','blocked','failed')) default 'running',
  failure_code text,
  permission_level text,
  data_start_date date,
  data_end_date date,
  current_rows integer not null default 0 check (current_rows >= 0),
  previous_rows integer not null default 0 check (previous_rows >= 0),
  summary jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default clock_timestamp()
);

create table if not exists public.search_console_observations (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.search_measurement_runs(id) on delete cascade,
  period text not null check (period in ('current_28d','previous_28d')),
  dimension_type text not null check (dimension_type in ('query','page','country','device','query_page')),
  key_1 text not null,
  key_2 text not null default '',
  canonical_path text,
  clicks double precision not null default 0 check (clicks >= 0),
  impressions double precision not null default 0 check (impressions >= 0),
  ctr double precision not null default 0 check (ctr >= 0 and ctr <= 1),
  position double precision not null default 0 check (position >= 0),
  observed_at timestamptz not null default clock_timestamp(),
  unique (run_id, period, dimension_type, key_1, key_2)
);

