-- Phase 5.2: verified Media Library reel and carousel render pipeline.
-- Safe to apply independently. No renderer secret is stored in database tables.

ALTER TABLE public.media_assets
  ADD COLUMN IF NOT EXISTS verification_status text NOT NULL DEFAULT 'pending',
  ADD COLUMN IF NOT EXISTS width_px integer,
  ADD COLUMN IF NOT EXISTS height_px integer,
  ADD COLUMN IF NOT EXISTS duration_ms integer,
  ADD COLUMN IF NOT EXISTS checksum_sha256 text,
  ADD COLUMN IF NOT EXISTS social_approved boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS social_approved_at timestamptz,
  ADD COLUMN IF NOT EXISTS social_approved_by uuid REFERENCES auth.users(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS media_assets_social_ready_idx
  ON public.media_assets (social_approved, verification_status, status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.social_render_jobs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 3 AND 120),
  render_type text NOT NULL CHECK (render_type IN ('reel','carousel')),
  aspect_ratio text NOT NULL CHECK (aspect_ratio IN ('9:16','4:5','1:1')),
  requested_duration_seconds integer NOT NULL DEFAULT 0 CHECK (requested_duration_seconds BETWEEN 0 AND 60),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','owner_review','queued','rendering','ready','failed','cancelled')),
  manifest jsonb NOT NULL DEFAULT '{}'::jsonb,
  renderer_provider text,
  renderer_job_id text,
  attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  locked_at timestamptz,
  output_asset_id uuid REFERENCES public.media_assets(id) ON DELETE SET NULL,
  output_url text,
  output_verification jsonb,
  error_message text,
  owner_approved_at timestamptz,
  owner_approved_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.social_render_job_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  job_id uuid NOT NULL REFERENCES public.social_render_jobs(id) ON DELETE CASCADE,
  media_asset_id uuid NOT NULL REFERENCES public.media_assets(id) ON DELETE RESTRICT,
  position integer NOT NULL CHECK (position BETWEEN 1 AND 10),
  duration_ms integer CHECK (duration_ms IS NULL OR duration_ms BETWEEN 100 AND 10000),
  scene_text text,
  overlay_text text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (job_id, position),
  UNIQUE (job_id, media_asset_id)
);

CREATE TABLE IF NOT EXISTS public.social_render_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id uuid REFERENCES public.social_render_jobs(id) ON DELETE SET NULL,
  event_type text NOT NULL,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  before_record jsonb,
  after_record jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS social_render_jobs_status_created_idx
