  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  item_id uuid REFERENCES public.social_calendar_items(id) ON DELETE CASCADE,
  recommendation_type text NOT NULL CHECK (recommendation_type IN ('collect_metrics','refresh_metrics','improve_cta','repurpose','pause_angle','review_tracking')),
  priority integer NOT NULL DEFAULT 50 CHECK (priority BETWEEN 1 AND 100),
  reason text NOT NULL,
  proposed_action text NOT NULL,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
