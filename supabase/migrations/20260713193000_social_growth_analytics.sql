CREATE TABLE IF NOT EXISTS public.social_metric_snapshots (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  item_id uuid NOT NULL REFERENCES public.social_calendar_items(id) ON DELETE CASCADE,
  platform text NOT NULL CHECK (platform IN ('facebook','instagram','linkedin','tiktok')),
  external_post_id text,
  external_post_url text,
  snapshot_at timestamptz NOT NULL DEFAULT now(),
  impressions bigint NOT NULL DEFAULT 0 CHECK (impressions >= 0),
  reach bigint NOT NULL DEFAULT 0 CHECK (reach >= 0),
  views bigint NOT NULL DEFAULT 0 CHECK (views >= 0),
  likes bigint NOT NULL DEFAULT 0 CHECK (likes >= 0),
  comments bigint NOT NULL DEFAULT 0 CHECK (comments >= 0),
  shares bigint NOT NULL DEFAULT 0 CHECK (shares >= 0),
  saves bigint NOT NULL DEFAULT 0 CHECK (saves >= 0),
  clicks bigint NOT NULL DEFAULT 0 CHECK (clicks >= 0),
  profile_visits bigint NOT NULL DEFAULT 0 CHECK (profile_visits >= 0),
  followers_delta bigint NOT NULL DEFAULT 0,
  source text NOT NULL CHECK (source IN ('meta_graph','linkedin_api','tiktok_api','generic_gateway','manual_verified')),
  verified boolean NOT NULL DEFAULT false,
  provider_snapshot_key text,
  raw_metrics jsonb NOT NULL DEFAULT '{}'::jsonb,
  collected_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (item_id, provider_snapshot_key)
);

