CREATE TABLE IF NOT EXISTS public.social_publish_runs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  worker_id text NOT NULL,
  trigger_source text NOT NULL CHECK (trigger_source IN ('admin','scheduler','retry')),
  status text NOT NULL DEFAULT 'running' CHECK (status IN ('running','completed','partial','failed')),
  claimed_count integer NOT NULL DEFAULT 0,
  published_count integer NOT NULL DEFAULT 0,
  manual_count integer NOT NULL DEFAULT 0,
  failed_count integer NOT NULL DEFAULT 0,
  summary jsonb NOT NULL DEFAULT '{}'::jsonb,
  error text,
  requested_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  started_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.social_publish_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id uuid REFERENCES public.social_calendar_items(id) ON DELETE SET NULL,
  run_id uuid REFERENCES public.social_publish_runs(id) ON DELETE SET NULL,
  event_type text NOT NULL CHECK (event_type IN ('render_attached','publication_approved','publication_revoked','claimed','published','verified_only','manual_required','failed')),
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  worker_id text,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

