CREATE TABLE IF NOT EXISTS public.social_platform_accounts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  platform text NOT NULL UNIQUE CHECK (platform IN ('facebook','instagram','linkedin','tiktok')),
  display_name text NOT NULL,
  external_account_id text,
  enabled boolean NOT NULL DEFAULT false,
  verification_status text NOT NULL DEFAULT 'missing' CHECK (verification_status IN ('missing','pending','verified','failed')),
  capabilities jsonb NOT NULL DEFAULT '{"text":false,"image":false,"carousel":false,"reel":false}'::jsonb,
  last_verified_at timestamptz,
  last_health jsonb NOT NULL DEFAULT '{}'::jsonb,
  connection_note text,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

